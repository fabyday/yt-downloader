const assert=require('node:assert/strict');
const {app,BrowserWindow}=require('electron');
const {once}=require('node:events');
process.env.UI_HARNESS_PORT='0';
const server=require('./ui-harness.cjs');
const ready=server.listening?Promise.resolve():once(server,'listening');
const deadline=setTimeout(()=>app.exit(1),30000);
app.whenReady().then(async()=>{
  await ready;const win=new BrowserWindow({show:false,width:1440,height:1000});
  await win.loadURL(`http://127.0.0.1:${server.address().port}/?view=editor&sourceUrl=https://www.youtube.com/watch?v=fixture`);
  const result=await win.webContents.executeJavaScript(`(async()=>{
    const wait=ms=>new Promise(r=>setTimeout(r,ms));
    while(document.querySelector('#endTime')?.textContent!=='10:00.000')await wait(50);
    const key=letter=>document.body.dispatchEvent(new KeyboardEvent('keydown',{key:letter.toLowerCase(),code:'Key'+letter,bubbles:true,cancelable:true}));
    const seek=async seconds=>{
      const input=document.querySelector('#timelineInput'),rect=input.getBoundingClientRect();
      const opts={bubbles:true,cancelable:true,pointerId:5,button:0,clientX:rect.left+rect.width*seconds/600,clientY:rect.top+5};
      input.dispatchEvent(new PointerEvent('pointerdown',opts));window.dispatchEvent(new PointerEvent('pointerup',opts));await wait(80);
    };
    const range=()=>[document.querySelector('#startTime').textContent,document.querySelector('#endTime').textContent];
    const setup=async()=>{key('E');document.querySelector('#resetSelectionButton').click();await seek(100);key('A');await seek(200);key('S');};
    await setup();await seek(50);key('S');const endCross=range();
    await setup();await seek(250);key('A');const startCross=range();
    await setup();
    const drag=(kind,time)=>{
      const track=document.querySelector('#timelineInput').getBoundingClientRect();
      const opts={bubbles:true,cancelable:true,pointerId:6,button:0,clientX:track.left+track.width*time/600,clientY:track.top+5};
      document.querySelector('#'+kind+'MarkerHandle').dispatchEvent(new PointerEvent('pointerdown',opts));window.dispatchEvent(new PointerEvent('pointerup',opts));
    };
    drag('start',250);const mouseStart=range();
    const tagsVisible=!document.querySelector('#markerSplitTags').classList.contains('hidden');
    const tag=document.querySelector('#splitStartMarker'),rect=tag.getBoundingClientRect();
    const opts={bubbles:true,cancelable:true,pointerId:7,button:0,clientX:rect.left+rect.width/2,clientY:rect.top+5};
    tag.dispatchEvent(new PointerEvent('pointerdown',opts));const noJump=range();
    window.dispatchEvent(new PointerEvent('pointermove',{...opts,clientX:opts.clientX-document.querySelector('#timelineInput').clientWidth*50/600}));
    window.dispatchEvent(new PointerEvent('pointerup',opts));const split=range();
    drag('end',150);const mouseEnd=range();
    document.querySelector('#addSegmentButton').click();await wait(50);
    const zeroRejected=document.querySelectorAll('#segmentList .segment-row').length===0;
    await setup();document.querySelector('#addSegmentButton').click();await wait(50);
    document.querySelector('#toggleSegmentListButton').click();await wait(50);
    const focus=document.querySelector('#addSegmentButton');focus.focus();focus.click();await wait(50);
    const notice=!!document.querySelector('.segment-notice span');
    const focused=document.activeElement===focus;
    const revealed=!document.querySelector('#segmentSidebar').hidden;
    const duplicateCount=document.querySelectorAll('#segmentList .segment-row').length;
    await wait(650);focus.click();await wait(500);const extended=!!document.querySelector('.segment-notice span');
    await wait(650);const dismissed=!document.querySelector('.segment-notice span');
    await seek(150);key('A');focus.click();await wait(50);const partialCount=document.querySelectorAll('#segmentList .segment-row').length;
    drag('start',200);await wait(80);
    return {endCross,startCross,mouseStart,tagsVisible,noJump,split,mouseEnd,zeroRejected,notice,focused,revealed,duplicateCount,extended,dismissed,partialCount};
  })()`);
  console.log(result);
  assert.deepEqual(result.endCross,['00:00.000','00:50.000']);
  assert.deepEqual(result.startCross,['04:10.000','10:00.000']);
  assert.deepEqual(result.mouseStart,['04:10.000','04:10.000']);
  assert.deepEqual(result.noJump,result.mouseStart);assert.equal(result.tagsVisible,true);
  assert.deepEqual(result.split,['03:20.000','04:10.000']);
  assert.deepEqual(result.mouseEnd,['02:30.000','02:30.000']);
  for(const key of ['zeroRejected','notice','focused','revealed','extended','dismissed'])assert.equal(result[key],true,key);
  assert.equal(result.duplicateCount,1);assert.equal(result.partialCount,2);
  if(process.argv.includes('--screenshot'))await require('node:fs/promises').writeFile('/tmp/kawai-marker-tags.png',(await win.webContents.capturePage()).toPNG());
  win.destroy();server.close();clearTimeout(deadline);app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
