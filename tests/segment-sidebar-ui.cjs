const assert = require('node:assert/strict');
const { app, BrowserWindow } = require('electron');
const { once } = require('node:events');
process.env.UI_HARNESS_PORT = '0';
process.env.UI_HARNESS_LOCALE = 'ko';
const server = require('./ui-harness.cjs');
const ready = server.listening ? Promise.resolve() : once(server, 'listening');
const deadline = setTimeout(() => app.exit(1), 30000);
app.whenReady().then(async () => {
  await ready;
  const win = new BrowserWindow({ show: false, width: 1440, height: 900 });
  const js = code => win.webContents.executeJavaScript(code);
  await win.loadURL(`http://127.0.0.1:${server.address().port}/?view=editor&platform=darwin&sourceUrl=https://www.youtube.com/watch?v=fixture`);
  const initial = await js(`(async()=>{
    const wait=ms=>new Promise(r=>setTimeout(r,ms));
    while(document.querySelector('#endTime')?.textContent!=='10:00.000')await wait(50);
    window.sidebarPlayer=window.mockPlayer;window.sidebarStage=document.querySelector('#playerStage');
    window.sidebarAdd=document.querySelector('#addSegmentButton');
    window.sidebarGeometry=()=>{
      const box=selector=>{const r=document.querySelector(selector).getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:r.width,height:r.height};};
      return {video:box('.preview-pane'),sidebar:box('#segmentSidebar'),timeline:box('.timeline-panel'),rules:box('.selection-rules-panel'),range:box('.markers'),dock:box('.editor-dock'),toggle:box('#toggleSegmentListButton'),prefs:box('#openPreferenceOverlayButton'),overflow:document.documentElement.scrollWidth>innerWidth};
    };
    window.sidebarAdd.click();await wait(100);
    return {geometry:window.sidebarGeometry(),count:document.querySelectorAll('#segmentList .segment-row').length};
  })()`);
  assert.equal(initial.count, 1);
  assert.ok(initial.geometry.sidebar.left >= initial.geometry.video.right);
  assert.equal(initial.geometry.sidebar.top, initial.geometry.video.top);
  assert.equal(initial.geometry.sidebar.height, initial.geometry.video.height);
  assert.ok(initial.geometry.timeline.top >= initial.geometry.video.bottom);
  assert.ok(initial.geometry.toggle.left >= initial.geometry.prefs.right);
  assert.equal(initial.geometry.overflow, false);
  assert.equal(initial.geometry.rules.top, initial.geometry.range.top);
  assert.equal(initial.geometry.rules.bottom, initial.geometry.range.bottom);
  assert.ok(initial.geometry.rules.right < initial.geometry.range.left);
  assert.ok(initial.geometry.video.height >= 380);
  const hidden = await js(`(async()=>{
    document.querySelector('#toggleSegmentListButton').click();await new Promise(r=>setTimeout(r,100));
    const marker=document.querySelector('#endMarkerHandle'),track=document.querySelector('#timelineInput').getBoundingClientRect();
    const opts={bubbles:true,cancelable:true,pointerId:6,button:0,clientX:track.left+track.width/2,clientY:track.top+5};
    marker.dispatchEvent(new PointerEvent('pointerdown',opts));window.dispatchEvent(new PointerEvent('pointerup',opts));
    document.querySelector('#addSegmentButton').click();await new Promise(r=>setTimeout(r,100));
    return {geometry:window.sidebarGeometry(),hidden:document.querySelector('#segmentSidebar').hidden,count:document.querySelectorAll('#segmentList .segment-row').length,samePlayer:window.sidebarPlayer===window.mockPlayer,sameStage:window.sidebarStage===document.querySelector('#playerStage'),sameAdd:window.sidebarAdd===document.querySelector('#addSegmentButton'),addVisible:document.querySelector('#addSegmentButton').getBoundingClientRect().width>0};
  })()`);
  assert.equal(hidden.hidden,true);assert.equal(hidden.count,2);assert.ok(hidden.geometry.video.width>initial.geometry.video.width);
  assert.ok(hidden.samePlayer&&hidden.sameStage&&hidden.sameAdd&&hidden.addVisible);
  await js(`document.querySelector('#toggleSegmentListButton').click();new Promise(r=>setTimeout(r,100))`);
  if(process.argv.includes('--screenshot'))await require('node:fs/promises').writeFile('/tmp/kawai-segment-sidebar.png',(await win.webContents.capturePage()).toPNG());
  win.setSize(1100,900);
  await js(`new Promise(r=>setTimeout(r,200))`);
  const korean=await js(`window.sidebarGeometry()`);
  assert.equal(korean.overflow,false);
  assert.ok(korean.rules.right<korean.range.left);
  assert.equal(korean.rules.top,korean.range.top);
  assert.ok(korean.video.height>=370);
  if(process.argv.includes('--screenshot'))await require('node:fs/promises').writeFile('/tmp/kawai-editor-ko.png',(await win.webContents.capturePage()).toPNG());
  win.setSize(960,660);
  const compact=await js(`(async()=>{await new Promise(r=>setTimeout(r,200));return {...window.sidebarGeometry(),height:innerHeight};})()`);
  console.log(JSON.stringify({initial,compact}));
  assert.equal(compact.overflow,false);assert.equal(compact.dock.top,compact.rules.top);assert.ok(compact.video.height>=140);
  assert.ok(compact.rules.right<compact.range.left);
  const reachable=await js(`(()=>{const workspace=document.querySelector('.youtube-workspace-view');workspace.scrollTop=workspace.scrollHeight;const button=document.querySelector('#setEndButton').getBoundingClientRect();return button.bottom<=workspace.getBoundingClientRect().bottom;})()`);
  assert.equal(reachable,true);
  if(process.argv.includes('--screenshot'))await require('node:fs/promises').writeFile('/tmp/kawai-segment-sidebar-compact.png',(await win.webContents.capturePage()).toPNG());
  const final=await js(`(async()=>{
    const wait=()=>new Promise(r=>setTimeout(r,100));
    for(let i=0;i<12;i++){
      const marker=document.querySelector('#endMarkerHandle'),track=document.querySelector('#timelineInput').getBoundingClientRect();
      const opts={bubbles:true,cancelable:true,pointerId:6,button:0,clientX:track.left+track.width*(i+1)/20,clientY:track.top+5};
      marker.dispatchEvent(new PointerEvent('pointerdown',opts));window.dispatchEvent(new PointerEvent('pointerup',opts));
      document.querySelector('#addSegmentButton').click();
    }await wait();
    const list=document.querySelector('#segmentList');
    const scrolls=list.scrollHeight>list.clientHeight;
    document.querySelector('#segmentList .segment-row button').click();await wait();
    const count=document.querySelectorAll('#segmentList .segment-row').length;
    document.querySelector('#clearSegmentsButton').click();await wait();
    return {scrolls,count,empty:document.querySelectorAll('#segmentList .segment-row').length===0};
  })()`);
  assert.equal(final.scrolls,true);assert.equal(final.count,12);assert.equal(final.empty,true);
  console.log('Sidebar layout/toggle, stable player and bindings, hidden-list add, remove/clear, independent scroll, compact viewport passed');
  win.destroy();server.close();clearTimeout(deadline);app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
