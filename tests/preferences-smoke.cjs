// Run after bundle:renderer:dev with Electron. Uses mock data only.
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { app, BrowserWindow } = require('electron');
app.disableHardwareAcceleration();
process.env.UI_HARNESS_PORT = '0';
const server = require('./ui-harness.cjs');
const ready = server.listening ? Promise.resolve() : once(server, 'listening');
const deadline = setTimeout(() => app.exit(1), 30000);
app.whenReady().then(async () => {
  await ready;
  const win = new BrowserWindow({ show: false, width: 1400, height: 1000 });
  const platform = process.argv.includes('--windows') ? 'win32' : 'darwin';
  await win.loadURL(`http://127.0.0.1:${server.address().port}/?view=editor&platform=${platform}&sourceUrl=https://www.youtube.com/watch?v=fixture`);
  await win.webContents.executeJavaScript(`new Promise(resolve => {
    const timer = setInterval(() => { if (document.querySelector('#loadButton')) { clearInterval(timer); resolve(); } }, 50);
  })`);
  const result = await win.webContents.executeJavaScript(`(async () => {
    const wait = () => new Promise(r => setTimeout(r, 100));
    const clickText = text => {
      const buttons = [...document.querySelectorAll('[role="dialog"] button')];
      const match = buttons.find(el => el.textContent.trim() === text);
      if (!match) throw new Error('Missing button ' + text + ': ' + buttons.map(el => el.textContent).join('|'));
      match.click();
    };
    document.querySelector('#toggleDownloadPanelButton').click(); await wait();
    const loadDisabled = document.querySelector('#loadButton').disabled;
    document.querySelector('#toggleDownloadPanelButton').click(); await wait();
    const loadEnabled = !document.querySelector('#loadButton').disabled;
    window.ytClipper.getCookieStatus = async () => ({ configured: false, count: 0, error: 'cookies.readFailed' });
    window.browserStillRunning = true;
    window.ytClipper.getBrowserCookieStatus = async () => ({ running: window.browserStillRunning });
    window.ytClipper.importBrowserCookies = () => new Promise(resolve => { window.finishCookieImport = () => resolve({ configured: true, count: 2 }); });
    document.querySelector('#openPreferenceOverlayButton').click(); await new Promise(r => setTimeout(r, 400));
    const panel = document.querySelector('[role="dialog"]');
    [...panel.querySelectorAll('[role="tab"]')].find(el => el.textContent === 'Cookies').click(); await wait();
    const extractingDisabled = [...panel.querySelectorAll('button')].find(el => el.textContent === 'Extract from browser').disabled;
    window.browserStillRunning = false;
    await new Promise(r => setTimeout(r, 2200));
    const before = panel.getBoundingClientRect().width;
    clickText('Extract from browser'); await wait();
    const busyWidth = panel.getBoundingClientRect().width;
    const overflow = panel.scrollWidth > panel.clientWidth + 1;
    const overflowing = [...panel.querySelectorAll('*')].filter(el => el.getBoundingClientRect().right > panel.getBoundingClientRect().right + 1).slice(0, 12).map(el => ({ tag: el.tagName, cls: el.className, width: el.getBoundingClientRect().width }));
    window.finishCookieImport(); await wait();
    [...panel.querySelectorAll('[role="tab"]')].find(el => el.textContent === 'Shortcuts').click(); await wait();
    const keyLabel = panel.querySelector('button[aria-label="Focus URL field"]').textContent;
    const button = panel.querySelector('button[aria-label="Small step forward"]');
    button.click(); await wait();
    button.dispatchEvent(new KeyboardEvent('keydown', { key: 'a', code: 'KeyA', bubbles: true, cancelable: true })); await wait();
    const duplicate = [...panel.querySelectorAll('[role="alert"]')].some(el => el.textContent.includes('Already assigned'));
    button.dispatchEvent(new KeyboardEvent('keydown', { key: 'k', code: 'KeyK', bubbles: true, cancelable: true })); await wait();
    clickText('Save changes'); await wait();
    const saved = await window.ytClipper.getPreferences();
    document.body.dispatchEvent(new KeyboardEvent('keydown', { key: 'k', code: 'KeyK', bubbles: true, cancelable: true })); await wait();
    const time = document.querySelector('#currentTime').textContent;
    document.querySelector('#openPreferenceOverlayButton').click(); await wait();
    [...document.querySelectorAll('[role="tab"]')].find(el => el.textContent === 'Shortcuts').click(); await wait();
    clickText('Reset all shortcuts'); await wait(); clickText('Save changes'); await wait();
    const reset = await window.ytClipper.getPreferences();
    return { keyLabel, extractingDisabled, loadDisabled, loadEnabled, before, busyWidth, overflow, overflowing, duplicate, binding: saved.shortcuts.smallForward, reset: reset.shortcuts.smallForward, time };
  })()`);
  console.log(JSON.stringify(result));
  assert.equal(result.keyLabel, platform === 'darwin' ? '⌘L' : 'CtrlL');
  assert.equal(result.extractingDisabled, false);
  assert.equal(result.loadDisabled, true);
  assert.equal(result.loadEnabled, true);
  assert.ok(Math.abs(result.before - result.busyWidth) < 1);
  assert.equal(result.overflow, false);
  assert.equal(result.duplicate, true);
  assert.equal(result.binding, 'K');
  assert.equal(result.reset, 'ArrowRight');
  assert.equal(result.time, '00:01.000');
  console.log(JSON.stringify(result));
  win.destroy(); server.close(); clearTimeout(deadline); app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
