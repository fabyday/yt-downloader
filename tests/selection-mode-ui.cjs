const assert=require('node:assert/strict');
const {app,BrowserWindow}=require('electron');
const {once}=require('node:events');
process.env.UI_HARNESS_PORT='0';
const server=require('./ui-harness.cjs');
const ready=server.listening?Promise.resolve():once(server,'listening');
const deadline=setTimeout(()=>app.exit(1),30000);
app.whenReady().then(async()=>{
  await ready;const win=new BrowserWindow({show:false,width:1440,height:1000});
  await win.loadURL(`http://127.0.0.1:${server.address().port}/?view=editor&sourceUrl=https://www.youtube.com/watch?v=fixture`);
  const result=await win.webContents.executeJavaScript(`(async()=>{
    const wait=ms=>new Promise(r=>setTimeout(r,ms));
    while(!window.mockPlayer||document.querySelector('#endTime')?.textContent!=='10:00.000')await wait(50);
    const key=letter=>document.body.dispatchEvent(new KeyboardEvent('keydown',{key:letter.toLowerCase(),code:'Key'+letter,bubbles:true,cancelable:true}));
    const seek=async seconds=>{
      const input=document.querySelector('#timelineInput'),rect=input.getBoundingClientRect();
      const opts={bubbles:true,cancelable:true,pointerId:5,button:0,clientX:rect.left+rect.width*seconds/600,clientY:rect.top+5};
      input.dispatchEvent(new PointerEvent('pointerdown',opts));window.dispatchEvent(new PointerEvent('pointerup',opts));await wait(80);
    };
    const read=()=>({time:window.mockPlayer.getCurrentTime(),start:document.querySelector('#startTime').textContent,end:document.querySelector('#endTime').textContent});
    const setup=async()=>{key('E');document.querySelector('#resetSelectionButton').click();await seek(100);key('A');await seek(200);key('S');};
    const defaultFree=document.querySelector('#selectionMode-free').getAttribute('aria-pressed');
    await setup();key('Q');await seek(0);const low=read();await seek(600);const high=read();
    await seek(199.95);document.querySelector('#playPauseButton').click();await wait(250);
    const clampStopped=window.mockPlayer.getPlayerState()!==1&&Math.abs(window.mockPlayer.getCurrentTime()-200)<0.001;
    await setup();key('W');await seek(50);const followLow=read();await seek(250);const followHigh=read();
    document.querySelector('#playPauseButton').click();await wait(200);document.querySelector('#playPauseButton').click();
    const followPlayback=document.querySelector('#endTime').textContent>'04:10.000';
    await setup();key('E');await seek(250);const free=read();
    document.querySelector('#playPauseButton').click();await wait(150);const freePlaying=window.mockPlayer.getPlayerState()===1;document.querySelector('#playPauseButton').click();
    const beforeMarker=window.mockPlayer.getCurrentTime();
    const marker=document.querySelector('#endMarkerHandle'),track=document.querySelector('#timelineInput').getBoundingClientRect();
    const markerEvent={bubbles:true,cancelable:true,pointerId:6,button:0,clientX:track.left+track.width*150/600,clientY:track.top+5};
    marker.dispatchEvent(new PointerEvent('pointerdown',markerEvent));window.dispatchEvent(new PointerEvent('pointerup',markerEvent));await wait(100);
    const freeMarkerIndependent=Math.abs(window.mockPlayer.getCurrentTime()-beforeMarker)<0.001;
    document.querySelector('#toggleDownloadPanelButton').click();await wait(150);
    const set=(id,value)=>document.querySelector('#'+id).dispatchEvent(new CustomEvent('kawai-renderer-select-set',{detail:{value}}));
    set('encodingPresetSelect','audio-flac');set('encodingModeSelect','custom');await wait(100);
    document.querySelector('.manual-encoding button:not([role="combobox"])').click();await wait(50);
    const copiedPreset=document.querySelector('#customExtensionSelect').value==='flac'&&document.querySelector('#customFfmpegArgs').value==='-vn -c:a flac';
    const manualDisabled=document.querySelector('#encodingPresetSelect').disabled;
    const manualVisible=document.querySelector('#customFfmpegArgs').getBoundingClientRect().height>0;
    document.querySelector('#customFfmpegArgs').value='-i other.mp4';document.querySelector('#downloadButton').click();await wait(100);
    const rejectedInvalid=(await window.ytClipper.getDownloadQueue()).length===0;
    document.querySelector('#customFfmpegArgs').value='-c:v libx264 -crf 22 -c:a aac';set('customExtensionSelect','mov');
    document.querySelector('#downloadButton').click();await wait(400);
    const queue=await window.ytClipper.getDownloadQueue();
    document.querySelector('#openPreferenceOverlayButton').click();await wait(200);
    const modal=document.querySelector('[role="dialog"]'),before=modal.getBoundingClientRect();
    [...document.querySelectorAll('[role="tab"]')].find(el=>el.textContent==='Shortcuts').click();await wait(150);
    const buttons=[...document.querySelectorAll('.shortcut-binding-button')];
    const widths=buttons.map(el=>el.getBoundingClientRect().width);
    const close=document.querySelector('.preference-close-button').getBoundingClientRect();
    const after=modal.getBoundingClientRect();
    const focus=document.querySelector('.shortcut-binding-button');focus.focus();
    const noFocusRing=getComputedStyle(focus).boxShadow==='none'&&getComputedStyle(focus).outlineStyle==='none';
    return {defaultFree,low,high,clampStopped,followLow,followHigh,followPlayback,free,freePlaying,freeMarkerIndependent,copiedPreset,rejectedInvalid,manualDisabled,manualVisible,payload:queue[0]?.payload,widths,close:{width:close.width,height:close.height},stable:before.height===after.height,noFocusRing};
  })()`);
  assert.equal(result.defaultFree,'true');assert.equal(result.low.time,100);assert.equal(result.high.time,200);
  assert.equal(result.followLow.start,'00:50.000');assert.equal(result.followLow.end,'03:20.000');
  assert.equal(result.followHigh.start,'00:50.000');assert.equal(result.followHigh.end,'04:10.000');
  assert.equal(result.clampStopped,true);assert.equal(result.followPlayback,true);
  assert.equal(result.freeMarkerIndependent,true);assert.equal(result.copiedPreset,true);assert.equal(result.rejectedInvalid,true);
  assert.ok(Math.abs(result.free.time-250)<0.001);assert.equal(result.free.start,'01:40.000');assert.equal(result.free.end,'03:20.000');assert.equal(result.freePlaying,true);
  assert.equal(result.manualDisabled,true);assert.equal(result.manualVisible,true);assert.equal(result.payload.encodingPreset,'custom');assert.equal(result.payload.customExtension,'mov');assert.match(result.payload.customFfmpegArgs,/-crf 22/);
  assert.equal(result.widths.length,16);assert.ok(result.widths.every(width=>width===220));assert.ok(result.close.width>=100&&result.close.height>=40);assert.equal(result.stable,true);assert.equal(result.noFocusRing,true);
  if(process.argv.includes('--screenshot')){
    const capture=async file=>{await require('node:fs/promises').writeFile(file,(await win.webContents.capturePage()).toPNG());console.log(file);};
    await capture('/tmp/kawai-preferences-modes.png');
    await win.webContents.executeJavaScript(`document.querySelector('.preference-close-button').click();new Promise(r=>setTimeout(r,100))`);
    await capture('/tmp/kawai-manual-encoding.png');
    await win.webContents.executeJavaScript(`document.querySelector('#toggleDownloadPanelButton').click();new Promise(r=>setTimeout(r,600))`);
    await capture('/tmp/kawai-selection-modes.png');
  }
  console.log('Selection modes/QWE, free playback, custom queue options, fixed shortcut widths/modal, close button and focus suppression passed');
  win.destroy();server.close();clearTimeout(deadline);app.exit(0);
}).catch(error=>{console.error(error);server.close();app.exit(1);});
